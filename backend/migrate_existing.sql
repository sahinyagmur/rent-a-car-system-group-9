-- RENT A CAR MANAGEMENT SYSTEM
-- Migration from the old four-table schema to the six-table schema.
--
-- BACK UP THE DATABASE BEFORE RUNNING.
-- Intended for a database with the original tables:
-- cars, customers, rentals, payments.
--
-- Do not run on the current rentacar_db database.
-- Review the existing schema before using this migration.

BEGIN;

-- 1. RENAME OLD PRIMARY KEYS

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'cars' AND column_name = 'id'
    ) THEN
        ALTER TABLE cars RENAME COLUMN id TO car_id;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'customers' AND column_name = 'id'
    ) THEN
        ALTER TABLE customers RENAME COLUMN id TO customer_id;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'customers' AND column_name = 'name'
    ) THEN
        ALTER TABLE customers RENAME COLUMN name TO full_name;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'rentals' AND column_name = 'id'
    ) THEN
        ALTER TABLE rentals RENAME COLUMN id TO rental_id;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'payments' AND column_name = 'id'
    ) THEN
        ALTER TABLE payments RENAME COLUMN id TO payment_id;
    END IF;
END $$;

-- 2. ADD MISSING CAR FIELDS

ALTER TABLE cars
ADD COLUMN IF NOT EXISTS license_plate VARCHAR(30);

ALTER TABLE cars
ADD COLUMN IF NOT EXISTS status VARCHAR(20);

-- Preserve compatibility with the old available column.

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'cars' AND column_name = 'available'
    ) THEN
        EXECUTE '
            UPDATE cars
            SET status = CASE
                WHEN available THEN ''Available''
                ELSE ''Rented''
            END
            WHERE status IS NULL
        ';
    END IF;
END $$;

UPDATE cars
SET status = 'Available'
WHERE status IS NULL;

UPDATE cars
SET license_plate = 'LEGACY-' || car_id::text
WHERE license_plate IS NULL
   OR BTRIM(license_plate) = '';

ALTER TABLE cars
ALTER COLUMN status SET DEFAULT 'Available';

ALTER TABLE cars
ALTER COLUMN status SET NOT NULL;

ALTER TABLE cars
ALTER COLUMN license_plate SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS
cars_license_plate_unique_idx
ON cars(license_plate);

-- 3. CREATE ROLES TABLE

CREATE TABLE IF NOT EXISTS roles (
    role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

-- 4. CREATE USERS TABLE

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role_id INTEGER NOT NULL
        REFERENCES roles(role_id) ON DELETE RESTRICT
);

-- 5. CREATE INDEXES

CREATE INDEX IF NOT EXISTS rentals_car_dates_idx
ON rentals(car_id, start_date, end_date);

CREATE INDEX IF NOT EXISTS payments_rental_idx
ON payments(rental_id);

CREATE INDEX IF NOT EXISTS users_role_idx
ON users(role_id);

COMMIT;
