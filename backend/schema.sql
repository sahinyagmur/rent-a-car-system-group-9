-- NEW EMPTY DATABASE ONLY. Do not run over an existing database.
CREATE TABLE IF NOT EXISTS cars (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 brand VARCHAR(100) NOT NULL,
 model VARCHAR(100) NOT NULL,
 license_plate VARCHAR(30) NOT NULL UNIQUE,
 year INTEGER NOT NULL CHECK (year BETWEEN 1886 AND 2100),
 price_per_day NUMERIC(12,2) NOT NULL CHECK (price_per_day >= 0),
 status VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Rented','Maintenance'))
);
CREATE TABLE IF NOT EXISTS customers (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 phone VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS rentals (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
 car_id INTEGER NOT NULL REFERENCES cars(id) ON DELETE RESTRICT,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 CONSTRAINT rental_date_order CHECK (end_date >= start_date)
);
CREATE TABLE IF NOT EXISTS payments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rental_id INTEGER NOT NULL REFERENCES rentals(id) ON DELETE RESTRICT,
 amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
 payment_method VARCHAR(10) NOT NULL CHECK (payment_method IN ('Cash','Card')),
 payment_status VARCHAR(10) NOT NULL CHECK (payment_status IN ('Paid','Pending'))
);
CREATE INDEX IF NOT EXISTS rentals_car_dates_idx ON rentals(car_id, start_date, end_date);
CREATE INDEX IF NOT EXISTS payments_rental_idx ON payments(rental_id);
