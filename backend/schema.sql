-- RENT A CAR MANAGEMENT SYSTEM (CMPE341 Group 9)
-- PostgreSQL physical schema. Run on a NEW, EMPTY database only.
-- docker compose runs this file automatically on the first start.

CREATE TABLE IF NOT EXISTS roles (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(20) NOT NULL UNIQUE
              CHECK (role_name IN ('admin', 'customer'))
);

CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,          -- werkzeug scrypt hash, never plain text
    role_id       INTEGER      NOT NULL REFERENCES roles(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS cars (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand         VARCHAR(100)  NOT NULL,
    model         VARCHAR(100)  NOT NULL,
    license_plate VARCHAR(30)   NOT NULL UNIQUE,
    year          INTEGER       NOT NULL CHECK (year BETWEEN 1886 AND 2100),
    price_per_day NUMERIC(12,2) NOT NULL CHECK (price_per_day >= 0),
    status        VARCHAR(20)   NOT NULL DEFAULT 'Available'
                  CHECK (status IN ('Available', 'Rented', 'Maintenance'))
);

CREATE TABLE IF NOT EXISTS customers (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Optional 1:1 link to a login account; walk-in customers added by staff have none.
    user_id           INTEGER UNIQUE REFERENCES users(id) ON DELETE SET NULL,
    name              VARCHAR(150) NOT NULL,
    email             VARCHAR(255) NOT NULL UNIQUE,
    phone             VARCHAR(30)  NOT NULL,
    driver_license_no VARCHAR(30)  NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS rentals (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER       NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    car_id      INTEGER       NOT NULL REFERENCES cars(id) ON DELETE RESTRICT,
    start_date  DATE          NOT NULL,
    end_date    DATE          NOT NULL,
    -- Price fixed at booking time, so later car price changes don't alter old rentals
    total_price NUMERIC(12,2) NOT NULL CHECK (total_price >= 0),
    status      VARCHAR(20)   NOT NULL DEFAULT 'Pending'
                CHECK (status IN ('Pending', 'Active', 'Completed', 'Cancelled')),
    CONSTRAINT rental_date_order CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS payments (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id      INTEGER       NOT NULL REFERENCES rentals(id) ON DELETE RESTRICT,
    payment_date   DATE          NOT NULL DEFAULT CURRENT_DATE,
    amount         NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_method VARCHAR(10)   NOT NULL CHECK (payment_method IN ('Cash', 'Card')),
    payment_status VARCHAR(10)   NOT NULL CHECK (payment_status IN ('Paid', 'Pending'))
);

CREATE INDEX IF NOT EXISTS rentals_car_dates_idx ON rentals(car_id, start_date, end_date);
CREATE INDEX IF NOT EXISTS rentals_customer_idx  ON rentals(customer_id);
CREATE INDEX IF NOT EXISTS payments_rental_idx   ON payments(rental_id);
CREATE INDEX IF NOT EXISTS users_role_idx        ON users(role_id);
