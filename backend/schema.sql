-- RENT A CAR MANAGEMENT SYSTEM
-- PostgreSQL Physical Database Schema
-- Run only on a new, empty database.
-- Do not run on the existing rentacar_db database.

CREATE TABLE IF NOT EXISTS roles (
    role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cars (
    car_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    license_plate VARCHAR(30) NOT NULL UNIQUE,
    year INTEGER NOT NULL CHECK (year BETWEEN 1886 AND 2100),
    price_per_day NUMERIC(12,2) NOT NULL CHECK (price_per_day >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available', 'Rented', 'Maintenance'))
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS rentals (
    rental_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL
        REFERENCES customers(customer_id) ON DELETE RESTRICT,
    car_id INTEGER NOT NULL
        REFERENCES cars(car_id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT rental_date_order CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id INTEGER NOT NULL
        REFERENCES rentals(rental_id) ON DELETE RESTRICT,
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_method VARCHAR(10) NOT NULL
        CHECK (payment_method IN ('Cash', 'Card')),
    payment_status VARCHAR(10) NOT NULL
        CHECK (payment_status IN ('Paid', 'Pending'))
);

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role_id INTEGER NOT NULL
        REFERENCES roles(role_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS rentals_car_dates_idx
    ON rentals(car_id, start_date, end_date);

CREATE INDEX IF NOT EXISTS payments_rental_idx
    ON payments(rental_id);

CREATE INDEX IF NOT EXISTS users_role_idx
    ON users(role_id);
